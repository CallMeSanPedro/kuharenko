using System;
using System.Collections.Generic;
using System.Collections.Specialized;
using System.ComponentModel;
using System.Reflection;
using System.Windows;
using System.Windows.Controls;
using System.Windows.Data;
using System.Windows.Threading;
using Store.Views.Localization;

namespace Store.Views.Filtering
{
    /// <summary>
    /// Ставит фильтр в шапку уже после того, как базовый грид записал свой Header.
    /// Подпись фильтра получает ключ этой шапки, поэтому смена языка меняет и её.
    /// </summary>
    public static class ColumnCheckFilterBehavior
    {
        public static readonly DependencyProperty IsEnabledProperty = DependencyProperty.RegisterAttached(
            "IsEnabled",
            typeof(bool),
            typeof(ColumnCheckFilterBehavior),
            new PropertyMetadata(false, OnIsEnabledChanged));

        public static readonly DependencyProperty HeaderTemplateProperty = DependencyProperty.RegisterAttached(
            "HeaderTemplate",
            typeof(DataTemplate),
            typeof(ColumnCheckFilterBehavior),
            new PropertyMetadata(null, OnHeaderTemplateChanged));

        public static bool GetIsEnabled(DependencyObject obj) => (bool)obj.GetValue(IsEnabledProperty);

        public static void SetIsEnabled(DependencyObject obj, bool value) => obj.SetValue(IsEnabledProperty, value);

        public static DataTemplate GetHeaderTemplate(DependencyObject obj) => (DataTemplate)obj.GetValue(HeaderTemplateProperty);

        public static void SetHeaderTemplate(DependencyObject obj, DataTemplate value) => obj.SetValue(HeaderTemplateProperty, value);

        private static readonly DependencyProperty ColumnsHandlerProperty = DependencyProperty.RegisterAttached(
            "ColumnsHandler",
            typeof(NotifyCollectionChangedEventHandler),
            typeof(ColumnCheckFilterBehavior),
            new PropertyMetadata(null));

        private static readonly List<DataGrid> Grids = new List<DataGrid>();

        static ColumnCheckFilterBehavior()
        {
            Translation.Instance.PropertyChanged += OnLanguageChanged;
        }

        private static void OnIsEnabledChanged(DependencyObject d, DependencyPropertyChangedEventArgs e)
        {
            var grid = d as DataGrid;
            if (grid == null)
                return;

            if ((bool)e.NewValue)
            {
                if (!Grids.Contains(grid))
                    Grids.Add(grid);
                grid.Loaded += OnLoaded;
                grid.AutoGeneratedColumns += OnAutoGeneratedColumns;
                grid.DataContextChanged += OnDataContextChanged;
                DependencyPropertyDescriptor.FromProperty(ItemsControl.ItemsSourceProperty, typeof(DataGrid))
                    .AddValueChanged(grid, OnItemsSourceChanged);
                var handler = new NotifyCollectionChangedEventHandler((sender, args) => Schedule(grid));
                grid.SetValue(ColumnsHandlerProperty, handler);
                grid.Columns.CollectionChanged += handler;
                Schedule(grid);
            }
            else
            {
                Grids.Remove(grid);
                grid.Loaded -= OnLoaded;
                grid.AutoGeneratedColumns -= OnAutoGeneratedColumns;
                grid.DataContextChanged -= OnDataContextChanged;
                DependencyPropertyDescriptor.FromProperty(ItemsControl.ItemsSourceProperty, typeof(DataGrid))
                    .RemoveValueChanged(grid, OnItemsSourceChanged);
                var handler = grid.GetValue(ColumnsHandlerProperty) as NotifyCollectionChangedEventHandler;
                if (handler != null)
                    grid.Columns.CollectionChanged -= handler;
                grid.ClearValue(ColumnsHandlerProperty);
            }
        }

        private static void OnHeaderTemplateChanged(DependencyObject d, DependencyPropertyChangedEventArgs e) => Schedule(d as DataGrid);

        private static void OnLoaded(object sender, RoutedEventArgs e) => Schedule((DataGrid)sender);

        private static void OnAutoGeneratedColumns(object sender, EventArgs e) => Schedule((DataGrid)sender);

        private static void OnDataContextChanged(object sender, DependencyPropertyChangedEventArgs e) => Schedule((DataGrid)sender);

        private static void OnItemsSourceChanged(object sender, EventArgs e) => Schedule(sender as DataGrid);

        private static void OnLanguageChanged(object sender, PropertyChangedEventArgs e)
        {
            if (e.PropertyName != "Item[]" && !string.IsNullOrEmpty(e.PropertyName))
                return;

            foreach (var grid in Grids.ToArray())
            {
                if (grid == null || grid.Dispatcher == null)
                    continue;
                grid.Dispatcher.BeginInvoke(DispatcherPriority.DataBind, new Action(() => RefreshLanguage(grid)));
            }
        }

        private static void Schedule(DataGrid grid)
        {
            if (grid == null)
                return;

            grid.Dispatcher.BeginInvoke(DispatcherPriority.ApplicationIdle, new Action(() => Apply(grid)));
        }

        private static void Apply(DataGrid grid)
        {
            var template = GetHeaderTemplate(grid);
            var filters = ResolveFilters(grid.DataContext);
            if (template == null || filters == null)
                return;

            foreach (var column in grid.Columns)
            {
                var installed = column.Header as ContentControl;
                var filter = installed == null ? null : installed.Content as ColumnHeaderFilter;
                if (filter == null)
                {
                    filter = filters.Find(column.SortMemberPath);
                    if (filter == null)
                        filter = filters.FindByTitle(HeaderText(column));
                }
                if (filter == null)
                    continue;

                BindCaption(grid, column, filter);
                if (installed != null && installed.Content == filter)
                    continue;

                column.HeaderTemplate = null;
                column.Header = new ContentControl
                {
                    Content = filter,
                    ContentTemplate = template,
                    Focusable = false,
                    VerticalAlignment = VerticalAlignment.Top
                };
            }
        }

        private static void RefreshLanguage(DataGrid grid)
        {
            if (grid == null || !GetIsEnabled(grid))
                return;

            foreach (var column in grid.Columns)
            {
                var control = column.Header as ContentControl;
                var filter = control == null ? null : control.Content as ColumnHeaderFilter;
                if (filter == null)
                    continue;

                BindCaption(grid, column, filter);
                var contentTemplate = control.ContentTemplate;
                if (contentTemplate == null)
                    continue;
                control.ContentTemplate = null;
                control.ContentTemplate = contentTemplate;
            }
        }

        private static void BindCaption(DataGrid grid, DataGridColumn column, ColumnHeaderFilter filter)
        {
            string key;
            string fallback;
            if (TryReadHeaderBinding(column, out key, out fallback))
            {
                filter.UseCaption(key, fallback);
                return;
            }

            // Шапка уже заменена фильтром, привязки больше нет.
            // Ключ, который есть в ресурсах, оставляем. Русский ShortName заменяем ключом колонки.
            var current = filter.CaptionKey;
            if (!string.IsNullOrEmpty(current) && Translation.Instance[current] != null)
                return;

            if (LocalizedColumnHeaders.TryReadCaption(grid, column.SortMemberPath, out key, out fallback))
                filter.UseCaption(key, fallback);
        }

        private static bool TryReadHeaderBinding(DataGridColumn column, out string key, out string fallback)
        {
            key = null;
            fallback = null;
            var binding = BindingOperations.GetBinding(column, DataGridColumn.HeaderProperty);
            if (binding == null || binding.Path == null)
                return false;

            var path = binding.Path.Path;
            if (string.IsNullOrEmpty(path) || path.Length < 2 || path[0] != '[' || path[path.Length - 1] != ']')
                return false;

            key = path.Substring(1, path.Length - 2);
            fallback = binding.ConverterParameter as string;
            return !string.IsNullOrEmpty(key);
        }

        private static string HeaderText(DataGridColumn column)
        {
            var text = column.Header as string;
            if (!string.IsNullOrEmpty(text))
                return text;

            var binding = BindingOperations.GetBinding(column, DataGridColumn.HeaderProperty);
            return binding == null ? null : binding.ConverterParameter as string;
        }

        private static ColumnHeaderFilterSet ResolveFilters(object dataContext)
        {
            if (dataContext == null)
                return null;

            var property = dataContext.GetType().GetProperty("HeaderFilters", BindingFlags.Instance | BindingFlags.Public);
            return property == null ? null : property.GetValue(dataContext, null) as ColumnHeaderFilterSet;
        }
    }
}
